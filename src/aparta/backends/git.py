"""git backend: per-profile gitconfig plus an includeIf merged into ~/.gitconfig."""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from ..i18n import _
from . import Note

from ..fsutil import SafeWriter, tilde
from ..profiles import Profile


def context_gitconfig_path(profile: Profile, home: Path) -> Path:
    return home / f".gitconfig-{profile.name}"


def render_context_gitconfig(profile: Profile) -> str:
    """Render the contents of ~/.gitconfig-<profile>."""
    lines = ["# Generated by aparta, profile: " + profile.name, "[user]"]
    if profile.git_name:
        lines.append(f"\tname = {profile.git_name}")
    lines.append(f"\temail = {profile.git_email}")
    if profile.ssh_key:
        key = profile.ssh_key
        lines += [
            "[core]",
            f'\tsshCommand = ssh -i {key} -o IdentitiesOnly=yes',
        ]
    if profile.ssh_alias:
        host = profile.git_host
        lines += [
            f'[url "git@{profile.ssh_alias}:"]',
            f"\tinsteadOf = https://{host}/",
            f"\tinsteadOf = git@{host}:",
        ]
    return "\n".join(lines) + "\n"


# ------------------------------------------------- per-profile gitconfig merge

# Keys aparta owns inside ~/.gitconfig-<profile>; everything else the user
# put there (name, signing, aliases, comments) is preserved untouched.

def _parse_sections(text: str) -> list[tuple[str | None, list[str]]]:
    """Split a gitconfig into (header, body lines), preserving raw text."""
    sections: list[tuple[str | None, list[str]]] = []
    header: str | None = None
    body: list[str] = []
    for line in text.splitlines():
        if line.lstrip().startswith("["):
            sections.append((header, body))
            header, body = line, []
        else:
            body.append(line)
    sections.append((header, body))
    return [s for s in sections if s[0] is not None or s[1]]


def _serialize_sections(sections: list[tuple[str | None, list[str]]]) -> str:
    out: list[str] = []
    for header, body in sections:
        if header is not None:
            out.append(header)
        out.extend(body)
    return "\n".join(out).rstrip("\n") + "\n"


def _section_index(sections: list[tuple[str | None, list[str]]], name: str) -> int | None:
    for i, (header, _body) in enumerate(sections):
        if header and re.match(rf"^\s*\[{re.escape(name)}\]\s*$", header, re.IGNORECASE):
            return i
    return None


def _set_key(sections: list[tuple[str | None, list[str]]], section: str, key: str, value: str) -> None:
    """Update the key in place when present, otherwise append it to the section."""
    line = f"\t{key} = {value}"
    index = _section_index(sections, section)
    if index is None:
        sections.append((f"[{section}]", [line]))
        return
    header, body = sections[index]
    pattern = re.compile(rf"^\s*{re.escape(key)}\s*=", re.IGNORECASE)
    for i, existing in enumerate(body):
        if pattern.match(existing):
            body[i] = line
            return
    insert_at = len(body)
    while insert_at > 0 and not body[insert_at - 1].strip():
        insert_at -= 1
    body.insert(insert_at, line)


def _set_url_insteadof(sections: list[tuple[str | None, list[str]]], alias: str, host: str) -> None:
    """Point the host's insteadOf block at the alias, updating an old one."""
    header = f'[url "git@{alias}:"]'
    body = [f"\tinsteadOf = https://{host}/", f"\tinsteadOf = git@{host}:"]
    for i, (existing_header, existing_body) in enumerate(sections):
        if existing_header and existing_header.lstrip().lower().startswith("[url "):
            text = "\n".join(existing_body)
            if f"https://{host}/" in text or f"git@{host}:" in text:
                sections[i] = (header, body)
                return
    sections.append((header, body))


def merge_context_gitconfig(existing_text: str, profile: Profile) -> str:
    """Merge the profile's settings into an existing gitconfig.

    Only the keys aparta manages are written; unknown sections, keys and
    comments survive. An empty input renders the file from scratch.
    """
    if not existing_text.strip():
        return render_context_gitconfig(profile)

    sections = _parse_sections(existing_text)
    if profile.git_name:
        _set_key(sections, "user", "name", profile.git_name)
    _set_key(sections, "user", "email", profile.git_email)
    if profile.ssh_key:
        _set_key(sections, "core", "sshCommand", f"ssh -i {profile.ssh_key} -o IdentitiesOnly=yes")
    if profile.ssh_alias:
        _set_url_insteadof(sections, profile.ssh_alias, profile.git_host)
    return _serialize_sections(sections)


def gitdir_pattern(profile: Profile) -> str:
    """gitdir pattern, keeping ~ when the root lives under home."""
    root = tilde(profile.root_path)
    if not root.endswith("/"):
        root += "/"
    return root


def render_includeif_block(gitdir: str, include_path: str) -> str:
    return f'[includeIf "gitdir:{gitdir}"]\n\tpath = {include_path}\n'


def has_includeif(gitconfig_text: str, gitdir: str) -> bool:
    """Whether an includeIf block for this gitdir already exists."""
    pattern = re.compile(
        r'\[includeIf\s+"gitdir:' + re.escape(gitdir) + r'"\]', re.IGNORECASE
    )
    return bool(pattern.search(gitconfig_text))


def merge_includeif(gitconfig_text: str, gitdir: str, include_path: str) -> str:
    """Append the includeIf block only if absent; preserve everything else."""
    if has_includeif(gitconfig_text, gitdir):
        return gitconfig_text
    block = render_includeif_block(gitdir, include_path)
    if gitconfig_text and not gitconfig_text.endswith("\n"):
        gitconfig_text += "\n"
    sep = "\n" if gitconfig_text else ""
    return gitconfig_text + sep + block


def remove_includeif(gitconfig_text: str, gitdir: str) -> str:
    """Drop the includeIf block for this gitdir, preserving everything else."""
    pattern = re.compile(
        r'\[includeIf\s+"gitdir:' + re.escape(gitdir) + r'"\]\s*\n(\s*path\s*=.*\n?)?',
        re.IGNORECASE,
    )
    return pattern.sub("", gitconfig_text)


def apply_git(profile: Profile, writer: SafeWriter, home: Path | None = None) -> list[Note]:
    """Write ~/.gitconfig-<profile> and merge its includeIf into ~/.gitconfig."""
    home = home or Path.home()
    ctx_path = context_gitconfig_path(profile, home)
    existing_ctx = ctx_path.read_text() if ctx_path.exists() else ""
    writer.write_text(ctx_path, merge_context_gitconfig(existing_ctx, profile))

    gitconfig = home / ".gitconfig"
    existing = gitconfig.read_text() if gitconfig.exists() else ""
    include_path = tilde(ctx_path) if home == Path.home() else str(ctx_path)
    merged = merge_includeif(existing, gitdir_pattern(profile), include_path)
    if merged != existing:
        writer.write_text(gitconfig, merged)

    return apply_adopted_git(profile, writer, home)


def apply_adopted_git(profile: Profile, writer: SafeWriter, home: Path | None = None) -> list[Note]:
    """Adopted repos (outside root): the local .git/config includes the
    profile's gitconfig, inheriting e-mail/key/insteadOf without moving."""
    notes: list[Note] = []
    if not profile.adopted_repos:
        return notes
    home = home or Path.home()
    include = str(context_gitconfig_path(profile, home))
    for raw in profile.adopted_repos:
        repo = Path(raw).expanduser()
        if not (repo / ".git").exists():
            notes.append(Note("warn", _("[yellow]warning:[/yellow] {repo} is not a git repository; skipping.", repo=repo)))
            continue
        current = subprocess.run(
            ["git", "-C", str(repo), "config", "--local", "--get-all", "include.path"],
            capture_output=True,
            text=True,
            timeout=30,
        )
        if include in current.stdout.splitlines():
            continue  # already adopted
        if writer.dry_run:
            notes.append(Note(
                "info",
                f"[yellow]--dry-run[/yellow] git -C {repo} config --local --add include.path {include}",
            ))
            continue
        r = subprocess.run(
            ["git", "-C", str(repo), "config", "--local", "--add", "include.path", include],
            capture_output=True,
            text=True,
            timeout=30,
        )
        if r.returncode != 0:
            notes.append(Note("error", _("[red]adopting {repo} failed:[/red] {error}", repo=repo, error=r.stderr.strip())))
        else:
            notes.append(Note("info", _("[green]git:[/green] {repo} adopted by profile '{name}'", repo=repo.name, name=profile.name)))
    return notes
